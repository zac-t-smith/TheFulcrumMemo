"""
fetch_ebp.py — Excess Bond Premium (EBP) data pipeline
================================================================

Pulls the monthly Excess Bond Premium series published by the Federal
Reserve Board alongside the FEDS Note "Updating the Recession Risk and
the Excess Bond Premium" (Favara, Gilchrist, Lewis, Zakrajšek, 2016+).

The note is re-published monthly; the CSV URL below is the stable
endpoint the Fed uses across all editions. The current link was verified
against the live FEDS Note landing page before this file was written
(per FULCRUM_V5_SPEC.md: "Find the current link from that note; don't
guess the URL").

Three series live in one CSV:
  - gz_spread : Gilchrist-Zakrajšek credit spread (percent)
  - ebp       : Excess Bond Premium (percent) — the v5 Cycle Probability
                model's primary leading indicator
  - est_prob  : Fed's model-implied 12-month recession probability (0-1)
                — kept as an independent cross-check on our own fit

Monthly observations dated to the first of the month, back to Jan 1973.

Run locally:
    python scripts/fetch_ebp.py

Run in CI: see .github/workflows/update-fulcrum-data.yml
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import sys
import time
from datetime import datetime
from pathlib import Path
from urllib.request import Request, urlopen
from urllib.error import HTTPError, URLError

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")

# Stable URL served alongside every monthly edition of the FEDS Note
# "Updating the Recession Risk and the Excess Bond Premium". Last verified
# live against the note's landing page; the note itself is at:
#   federalreserve.gov/econres/notes/feds-notes/
#     updating-the-recession-risk-and-the-excess-bond-premium-20161006.html
EBP_CSV_URL = "https://www.federalreserve.gov/econres/notes/feds-notes/ebp_csv.csv"


def fetch_csv(url: str, *, max_retries: int = 3, timeout: int = 60) -> str:
    """Fetch the raw CSV text with exponential backoff."""
    last_err: Exception | None = None
    for attempt in range(max_retries):
        try:
            req = Request(url, headers={"User-Agent": "fulcrum-memo-pipeline/1.0"})
            with urlopen(req, timeout=timeout) as resp:
                return resp.read().decode("utf-8")
        except (HTTPError, URLError, TimeoutError) as e:
            last_err = e
            if attempt < max_retries - 1:
                time.sleep(2 ** attempt)
    raise RuntimeError(f"EBP fetch failed after {max_retries} attempts: {last_err}")


def parse_rows(csv_text: str) -> list[dict[str, float | str]]:
    """Parse the Fed's EBP CSV. Enforces the expected schema."""
    reader = csv.DictReader(io.StringIO(csv_text))
    expected = {"date", "gz_spread", "ebp", "est_prob"}
    if reader.fieldnames is None or set(reader.fieldnames) != expected:
        raise RuntimeError(
            f"Unexpected EBP schema. Got {reader.fieldnames}, expected {sorted(expected)}."
        )

    rows: list[dict[str, float | str]] = []
    for raw in reader:
        try:
            # Normalize the date — the Fed's CSV uses YYYY-MM-DD already,
            # but assert it to catch any schema drift.
            d = datetime.strptime(raw["date"], "%Y-%m-%d").date()
            rows.append({
                "date": d.isoformat(),
                "gz_spread": float(raw["gz_spread"]),
                "ebp": float(raw["ebp"]),
                "est_prob": float(raw["est_prob"]),
            })
        except (KeyError, ValueError):
            # Skip malformed rows; log so CI surfaces them.
            print(f"⚠️  Skipping malformed EBP row: {raw}", file=sys.stderr)
            continue
    return rows


def write_csv(rows: list[dict[str, float | str]], path: Path) -> None:
    """Persist the raw CSV alongside the other FRED CSVs for the backtest workbook."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["date", "gz_spread", "ebp", "est_prob"])
        for r in rows:
            w.writerow([r["date"], r["gz_spread"], r["ebp"], r["est_prob"]])


def write_typescript(rows: list[dict[str, float | str]], path: Path) -> None:
    """Emit a single TS file carrying all three EBP columns, keyed by date."""
    path.parent.mkdir(parents=True, exist_ok=True)

    first = rows[0]["date"] if rows else "n/a"
    last = rows[-1]["date"] if rows else "n/a"

    lines: list[str] = []
    lines.append("// AUTO-GENERATED by scripts/fetch_ebp.py — DO NOT EDIT BY HAND.")
    lines.append("// Source: Federal Reserve Board, FEDS Note")
    lines.append("//   \"Updating the Recession Risk and the Excess Bond Premium\"")
    lines.append(f"//   CSV endpoint: {EBP_CSV_URL}")
    lines.append(f"// Coverage: {first} → {last} ({len(rows)} obs)")
    lines.append(f"// Generated: {datetime.utcnow().isoformat()}Z")
    lines.append("")
    lines.append("export interface EbpMonthlyPoint {")
    lines.append("  /** First of month, YYYY-MM-DD. */")
    lines.append("  date: string;")
    lines.append("  /** Gilchrist-Zakrajšek credit spread (percent). */")
    lines.append("  gzSpread: number;")
    lines.append("  /** Excess Bond Premium — residual after controlling for default risk (percent). */")
    lines.append("  ebp: number;")
    lines.append("  /** Fed model-implied 12-month US recession probability (0-1). */")
    lines.append("  fedRecessionProb: number;")
    lines.append("}")
    lines.append("")
    lines.append("export const ebpHistory: EbpMonthlyPoint[] = [")
    for r in rows:
        lines.append(
            f'  {{ date: "{r["date"]}", '
            f'gzSpread: {r["gz_spread"]:.6f}, '
            f'ebp: {r["ebp"]:.6f}, '
            f'fedRecessionProb: {r["est_prob"]:.6f} }},'
        )
    lines.append("];")
    lines.append("")
    lines.append("export const ebpHistoryMeta = {")
    lines.append(f'  sourceUrl: "{EBP_CSV_URL}",')
    lines.append('  sourceNote: "Favara, Gilchrist, Lewis, Zakrajšek — FEDS Note, updated monthly",')
    lines.append(f'  firstObservation: "{first}",')
    lines.append(f'  lastObservation: "{last}",')
    lines.append(f"  observationCount: {len(rows)},")
    lines.append("} as const;")
    lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Fulcrum Memo EBP data pipeline")
    parser.add_argument("--data-dir", default="data", help="CSV output dir")
    parser.add_argument("--ts-dir", default="src/data", help="TS output dir")
    parser.add_argument("--summary-out", help="Write JSON summary for CI")
    args = parser.parse_args()

    summary: dict[str, object] = {
        "started_at": datetime.utcnow().isoformat() + "Z",
        "source_url": EBP_CSV_URL,
    }

    try:
        print(f"  Fetching EBP from {EBP_CSV_URL} …", flush=True)
        text = fetch_csv(EBP_CSV_URL)
        rows = parse_rows(text)
        if not rows:
            raise RuntimeError("EBP CSV parsed to zero rows")
    except RuntimeError as e:
        # Follow the FRED pipeline's partial-failure philosophy: one down
        # series must not fail the whole data job. Surface the error and
        # exit 0 so the daily commit still includes other series.
        print(f"❌ EBP: {e}", file=sys.stderr)
        summary["status"] = "error"
        summary["error"] = str(e)
        summary["completed_at"] = datetime.utcnow().isoformat() + "Z"
        if args.summary_out:
            Path(args.summary_out).write_text(json.dumps(summary, indent=2))
        return 0

    csv_path = Path(args.data_dir) / "ebp.csv"
    ts_path = Path(args.ts_dir) / "ebpHistory.ts"
    write_csv(rows, csv_path)
    write_typescript(rows, ts_path)

    first = rows[0]["date"]
    last = rows[-1]["date"]
    print(f"  ✓ EBP: {len(rows):,} rows, {first} → {last}")

    summary["status"] = "ok"
    summary["row_count"] = len(rows)
    summary["first_date"] = first
    summary["latest_date"] = last
    summary["csv_path"] = str(csv_path)
    summary["ts_path"] = str(ts_path)
    summary["completed_at"] = datetime.utcnow().isoformat() + "Z"
    if args.summary_out:
        Path(args.summary_out).write_text(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
